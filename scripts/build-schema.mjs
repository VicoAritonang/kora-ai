// Builds the SQL files that are applied by hand (Neon SQL editor / psql) and
// the goose migration from one source:
//
//   db/schema.app.sql + db/river.sql  →  db/schema.sql          (apply once)
//                                     →  migrations/…_init.sql  (goose)
//   data/norms/*.json                 →  db/seed.sql
//
// Run: node scripts/build-schema.mjs
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n");

const app = read("db/schema.app.sql");
const river = read("db/river.sql");
const riverVersions = [...river.matchAll(/^-- River main migration (\d+) \[up\]/gm)].map((m) => Number(m[1]));

const riverMark = `
-- Record the River migrations as applied, so River's own migrator (if ever
-- used) does not try to re-run them.
insert into river_migration (line, version)
select 'main', v from unnest(array[${riverVersions.join(", ")}]::bigint[]) as v
on conflict do nothing;
`;

const header = `-- =====================================================================
-- Kora AI — full database schema. GENERATED by scripts/build-schema.mjs.
-- Apply once on an empty database:
--   psql "$NEON_DB_URL" -f db/schema.sql      (or paste in the Neon SQL editor)
-- Then load reference data:
--   psql "$NEON_DB_URL" -f db/seed.sql
-- =====================================================================
`;

const body = `${app}\n-- ===================== River job queue (v0.51.2, line "main") =========\n${river}\n${riverMark}`;
writeFileSync(join(root, "db/schema.sql"), `${header}\nbegin;\n\n${body}\ncommit;\n`);

// Goose migration: same Up; Down drops everything.
const down = `
drop table if exists idempotency_keys, feedback, reminders, outbound_clicks, package_items, package_days cascade;
alter table if exists conversations drop constraint if exists conversations_selected_package_fk;
drop table if exists packages, fx_rates, price_cache, cost_norms, offers, trip_requests, tool_artifacts, run_events, runs, messages, conversations, magic_link_tokens, auth_sessions, auth_identities, users cascade;
drop function if exists kora_ensure_run_events_partition(date);
drop type if exists event_visibility, price_kind, item_category, feasibility, package_status, package_tier, offer_kind, run_mode, run_status, message_role;
drop table if exists river_notification, river_queue, river_leader, river_job, river_migration cascade;
drop function if exists river_job_state_in_bitmask(bit, river_job_state), river_job_notify() cascade;
drop type if exists river_job_state;
`;
writeFileSync(
  join(root, "migrations/20261115000001_init.sql"),
  `-- GENERATED by scripts/build-schema.mjs from db/schema.app.sql + db/river.sql\n-- +goose Up\n-- +goose StatementBegin\n${body}\n-- +goose StatementEnd\n\n-- +goose Down\n-- +goose StatementBegin\n${down}-- +goose StatementEnd\n`,
);

// Seed: cost norms from data/norms/*.json (curated, reviewed files).
const q = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const uuidFrom = (s) => {
  // Same as Go uuid.NewSHA1(uuid.Nil, s): SHA-1 over a 16-byte zero namespace + name.
  const h = createHash("sha1").update(Buffer.alloc(16)).update(s).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-${((parseInt(h.slice(16, 18), 16) & 0x3f) | 0x80).toString(16)}${h.slice(18, 20)}-${h.slice(20, 32)}`;
};
let seed = `-- GENERATED by scripts/build-schema.mjs from data/norms/*.json.
-- Cost norms are reference numbers for estimate items. Re-running is safe:
-- rows are keyed by a stable id and updated in place only while unreferenced.
begin;
`;
for (const f of readdirSync(join(root, "data/norms")).filter((f) => f.endsWith(".json")).sort()) {
  const doc = JSON.parse(read(`data/norms/${f}`));
  seed += `\n-- ${f}: ${doc.destination_code} (${doc.status})\n`;
  for (const n of doc.norms) {
    const id = uuidFrom(`${doc.destination_code}:${n.key}`);
    const details = JSON.stringify({ ...(n.details || {}), key: n.key, status: doc.status });
    seed += `insert into cost_norms (id, destination_code, category, tier, label, unit, amount, currency, child_factor, details, source_label, source_url, verified_at, valid_from, valid_to)
values (${q(id)}, ${q(doc.destination_code)}, ${q(n.category)}, ${q(n.tier)}, ${q(n.label)}, ${q(n.unit)}, ${n.amount}, ${q(n.currency)}, ${n.child_factor ?? "null"}, ${q(details)}::jsonb, ${q(n.source_label ?? doc.source_label)}, ${q(n.source_url)}, ${q(n.verified_at ?? doc.verified_at)}, ${q(n.valid_from)}, ${q(n.valid_to)})
on conflict (id) do update set label = excluded.label, amount = excluded.amount, currency = excluded.currency, child_factor = excluded.child_factor, details = excluded.details, source_label = excluded.source_label, source_url = excluded.source_url, verified_at = excluded.verified_at, updated_at = now()
  where not exists (select 1 from package_items pi where pi.norm_id = cost_norms.id);
`;
  }
}
seed += "\ncommit;\n";
writeFileSync(join(root, "db/seed.sql"), seed);
console.log(`schema.sql, migration and seed.sql written (River versions ${riverVersions.join(",")})`);
