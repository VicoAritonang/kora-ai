export type Locale = "en" | "id";
const dicts: Record<Locale, Dict> = { id, en };
const STORE = "kora.locale";
export const DEFAULT_LOCALE: Locale = "en";

type Ctx = { t: Dict; locale: Locale; setLocale: (l: Locale) => void };
const Ctx = createContext<Ctx>({ t: en, locale: DEFAULT_LOCALE, setLocale: () => {} });

function stored(): Locale {
  try {
    const v = localStorage.getItem(STORE);
    return v === "id" || v === "en" ? v : DEFAULT_LOCALE;
  } catch {
    return DEFAULT_LOCALE;
  }
}

/** The traveller's language: remembered per browser, English by default. */
export function I18nProvider({ children, onChange }: { children: ReactNode; onChange?: (l: Locale) => void }) {
  const [locale, setState] = useState<Locale>(DEFAULT_LOCALE);
  useEffect(() => setState(stored()), []);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const setLocale = useCallback(
    (l: Locale) => {
      try {
        localStorage.setItem(STORE, l);
      } catch {
        /* storage unavailable: the choice lasts for this page only */
      }
      setState(l);
      onChange?.(l);
    },
    [onChange],
  );
  // Format helpers (money, dates) read the locale during render.
  setFormatLocale(locale === "en" ? "en-US" : "id-ID");
  const value = useMemo(() => ({ t: dicts[locale], locale, setLocale }), [locale, setLocale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useT(): Dict {
  return useContext(Ctx).t;
}

export function useLocale(): { locale: Locale; setLocale: (l: Locale) => void } {
  const { locale, setLocale } = useContext(Ctx);
  return { locale, setLocale };
}
